def progress(a1, r, n):
    # Базовый случай: первый член прогрессии уже известен
    if n == 1:
        return a1
    # Рекурсивный шаг: n-й член — это (n-1)-й член плюс разность r
    return progress(a1, r, n - 1) + r

# Пример: a1=2, r=3, найти 5-й член (2, 5, 8, 11, 14)
print(progress(2, 3, 5))  # Выведет 14
